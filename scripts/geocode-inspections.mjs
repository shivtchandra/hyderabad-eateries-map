// Finds the real location of food safety records that aren't spots on our map
// (licence suspended / closed by default), so the food safety filter and map can
// pin them. Google Places "find place", biased to Hyderabad. A result is kept
// only when Google's address contains the record's area AND the names share a
// word; anything else is printed for a human and left off the map.
//
//   node scripts/geocode-inspections.mjs [--all-actions]
// Writes data/inspection-places.json (re-runs skip records already resolved).
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { config } from "dotenv";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
config({ path: path.join(__dirname, "..", ".env.local") });
const KEY = process.env.GOOGLE_MAPS_API_KEY;
if (!KEY) { console.error("GOOGLE_MAPS_API_KEY missing"); process.exit(1); }

const ACTIONS = process.argv.includes("--all-actions") ? null : new Set(["licence-suspended", "closed"]);
const OUT = path.join(__dirname, "..", "data", "inspection-places.json");
const drives = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "inspection-drives.json"), "utf8"));
const links = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "inspection-links.json"), "utf8")).links || [];
const prev = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, "utf8")).places || [] : [];

const norm = (s = "") => s.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, " ").trim();
const STOP = new Set("the restaurant restaurants hotel family and pvt ltd private limited multicuisine multi cuisine kitchen bar foods food n co sri shree new hyderabad unit a of".split(" "));
const words = (s) => norm(s).split(" ").filter((t) => t.length > 2 && !STOP.has(t));
const key = (date, name) => `${date}|${norm(name)}`;
const linked = new Set(links.map((l) => key(l.date, l.name)));
const done = new Map(prev.map((p) => [key(p.date, p.name), p]));

async function findPlace(query) {
  const url = new URL("https://maps.googleapis.com/maps/api/place/findplacefromtext/json");
  url.searchParams.set("input", query);
  url.searchParams.set("inputtype", "textquery");
  url.searchParams.set("fields", "place_id,name,geometry,formatted_address,business_status");
  url.searchParams.set("locationbias", "circle:40000@17.40,78.47");
  url.searchParams.set("key", KEY);
  const data = await (await fetch(url)).json();
  return data.status === "OK" ? data.candidates[0] : null;
}

const out = [...prev];
for (const d of drives) {
  for (const en of d.entries || []) {
    if (en.spotId || linked.has(key(d.date, en.name))) continue;
    if (ACTIONS && !ACTIONS.has(en.action)) continue;
    if (done.has(key(d.date, en.name))) continue;
    const c = await findPlace(`${en.name}, ${en.area || ""}, Hyderabad`);
    const addr = norm(c?.formatted_address);
    const areaWords = norm(en.area).split(" ").filter((w) => w.length > 2 && !["near", "mall", "road"].includes(w));
    const areaOk = !!c && areaWords.some((w) => addr.includes(w));
    const gw = new Set(words(c?.name));
    const nameOk = !!c && words(en.name).some((w) => gw.has(w));
    const ok = areaOk && nameOk;
    console.log(`${ok ? "OK  " : "SKIP"} ${en.name} | ${en.area} => ${c ? `${c.name} | ${c.formatted_address}` : "no result"}`);
    out.push({
      date: d.date, name: en.name, area: en.area || null, verified: ok,
      ...(c ? { placeId: c.place_id, googleName: c.name, address: c.formatted_address, lat: c.geometry.location.lat, lng: c.geometry.location.lng } : {}),
    });
  }
}
fs.writeFileSync(OUT, JSON.stringify({
  _about: "Locations for food safety records that are not spots on our map. Only verified:true entries are pinned (Google address matched the record's area and the names share a word). Generated by scripts/geocode-inspections.mjs; set verified by hand after checking.",
  places: out,
}, null, 2) + "\n");
console.log(`\n${out.filter((p) => p.verified).length} verified of ${out.length}`);
